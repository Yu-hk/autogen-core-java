package com.example.agentcore.agent;

import java.util.Set;

/**
 * 会改变外部状态的工具（写文件、改文件、落库……）自己声明一下。
 *
 * <p><b>为什么需要这个标记：</b>{@link ChatAgent} 会拦掉"同名同参"的重复调用——这条规则对
 * 只读工具成立（同一份数据问两遍结果一样），对有副作用的工具不成立：
 * 编码场景里最常见的动作就是<b>改完代码再用同样的命令编译一次</b>。少了这个标记，
 * 第二次编译会被当成重复调用拦掉，模型只能靠加个假参数才绕得过去——实测就发生过，
 * 白烧了 6 次工具调用。</p>
 *
 * <p>声明的是"工具里哪些方法有副作用"（方法名＝工具名），因为同一个类里通常既有读也有写。</p>
 */
public interface MutatingTool {

    /** 有副作用的方法名，值是与 {@code @Tool(name=...)} 一致的工具名。 */
    Set<String> mutatingTools();
}
